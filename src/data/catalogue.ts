export function getProductsByCategory(categoryCode: string): ProductItem[] {
  if (categoryCode === 'ALL') return PRODUCTS;
  return PRODUCTS.filter(p => p.categoryCode === categoryCode);
}

export function searchProducts(query: string): ProductItem[] {
  const q = query.toLowerCase().trim();
  if (!q) return PRODUCTS;
  return PRODUCTS.filter(p => 
    p.name.toLowerCase().includes(q) ||
    p.brand.toLowerCase().includes(q) ||
    p.categoryName.toLowerCase().includes(q) ||
    p.sku.toLowerCase().includes(q)
  );
}

